import tempfile
import threading
import unittest
from pathlib import Path

import numpy as np
import pandas as pd

from csv_analyzer.analysis import build_filter_mask
from csv_analyzer.data import CancelledError, DataError, ImportOptions, load_dataset
from csv_analyzer.state import AppState, FilterRule


class ImportTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)

    def write(self, text, name="data.csv", encoding="utf-8"):
        path = Path(self.temp.name) / name
        path.write_text(text, encoding=encoding)
        return path

    def test_dat_commented_header_preserves_first_row(self):
        ds = load_dataset(self.write("# x y\n1 2\n3 4\n", "scan.dat"))
        self.assertEqual(ds.frame.values.tolist(), [[1, 2], [3, 4]])
        self.assertEqual(list(ds.frame), ["x", "y"])

    def test_headerless_dat_and_ordinary_header(self):
        ds = load_dataset(self.write("1 2\n3 4\n", "scan.dat"))
        self.assertEqual(len(ds.frame), 2)
        ds = load_dataset(self.write("x y\n1 2\n", "scan.dat"), ImportOptions(header="yes"))
        self.assertEqual(ds.frame.values.tolist(), [[1, 2]])

    def test_explicit_dat_header_skips_leading_metadata_comments(self):
        path = self.write("# generated by instrument\n# run 42\nx y\n1 2\n", "scan.dat")
        ds = load_dataset(path, ImportOptions(header="yes"))
        self.assertEqual(ds.frame.columns.tolist(), ["x", "y"])
        self.assertEqual(ds.frame.values.tolist(), [[1, 2]])

    def test_csv_delimiters_decimal_and_encoding(self):
        path = self.write("café;value\na;1,5\n", encoding="cp1252")
        ds = load_dataset(path, ImportOptions(encoding="cp1252", decimal=","))
        self.assertEqual(ds.frame["value"].iloc[0], 1.5)
        self.assertEqual(ds.delimiter, ";")
        with self.assertRaises(DataError):
            load_dataset(path)

    def test_quoted_newlines_and_delimiters(self):
        ds = load_dataset(self.write('label,x\n"a,b",1\n"two\nlines",2\n'))
        self.assertEqual(ds.frame["label"].tolist(), ["a,b", "two\nlines"])

    def test_unicode_nul_is_rejected_in_csv_data_and_headers(self):
        cases = (
            ("cell", "name,value\nabc\x00def,1\nxyz,2\n"),
            ("quoted multiline", 'name,value\n"abc\x00def\nmore",1\nxyz,2\n'),
            ("header", "na\x00me,value\nabc,1\n"),
        )
        for label, text in cases:
            with self.subTest(label=label):
                with self.assertRaisesRegex(DataError, "Unicode NUL"):
                    load_dataset(self.write(text, f"{label.replace(' ', '_')}.csv"))

    def test_unicode_nul_is_rejected_in_dat_data_headers_and_comments(self):
        cases = (
            (
                "data field",
                '"abc\x00def" 1\nxyz 2\n',
                ImportOptions(header="no"),
            ),
            (
                "commented header",
                "# na\x00me value\nabc 1\n",
                ImportOptions(),
            ),
            (
                "ignored comment",
                "# instrument\x00note\nx y\n1 2\n",
                ImportOptions(header="yes"),
            ),
        )
        for label, text, options in cases:
            with self.subTest(label=label):
                path = self.write(text, f"{label.replace(' ', '_')}.dat")
                with self.assertRaisesRegex(DataError, "Unicode NUL"):
                    load_dataset(path, options)

    def test_utf16_zero_bytes_are_not_mistaken_for_unicode_nul(self):
        path = self.write("name,value\nalpha,1\nbeta,2\n", "utf16.csv", encoding="utf-16")
        ds = load_dataset(path, ImportOptions(encoding="utf-16", delimiter=","))
        self.assertEqual(ds.frame["name"].tolist(), ["alpha", "beta"])

    def test_blank_lines_and_quoted_empty_records_are_distinct(self):
        ds = load_dataset(self.write(' \t \nvalue\n   \n""\n"   "\n5\n\t\n'))
        self.assertEqual(len(ds.frame), 3)
        self.assertTrue(ds.frame.iloc[0].isna().all())
        self.assertEqual(ds.frame.iloc[1, 0], "   ")
        ds = load_dataset(self.write("x,y\n  \n1,2\n\t \n3,4\n"))
        self.assertEqual(ds.frame.values.tolist(), [[1, 2], [3, 4]])

    def test_dat_literal_apostrophes_backslashes_and_quoted_comments(self):
        ds = load_dataset(
            self.write('# "a label" value\n"a # b" 1 # note\ndon\'t 2\nC:\\data 3\n', "scan.dat")
        )
        self.assertEqual(ds.frame.columns.tolist(), ["a label", "value"])
        self.assertEqual(ds.frame.iloc[:, 0].tolist(), ["a # b", "don't", "C:\\data"])
        ds = load_dataset(self.write('# "a ""quote""" y\n1 2\n', "scan.dat"))
        self.assertEqual(ds.frame.columns.tolist(), ['a "quote"', "y"])

    def test_dat_quoted_empty_field_and_malformed_quote(self):
        ds = load_dataset(self.write('# x y\n"" 2\n', "scan.dat"))
        self.assertEqual(ds.missing_count, 1)
        with self.assertRaisesRegex(DataError, "Unclosed quote"):
            load_dataset(self.write('# x y\n"unfinished 2\n', "scan.dat"))

    def test_bad_widths_never_infer_an_index(self):
        for text in ("x,y\n1,2,3\n4,5,6\n", "x,y\n1,2\n3\n"):
            with self.subTest(text=text), self.assertRaises(DataError):
                load_dataset(self.write(text))

    def test_empty_and_header_only(self):
        with self.assertRaises(DataError):
            load_dataset(self.write(""))
        ds = load_dataset(self.write("x,y\n"))
        self.assertEqual(ds.frame.shape, (0, 2))
        self.assertTrue(ds.notices)

    def test_duplicate_blank_and_colliding_headers(self):
        ds = load_dataset(self.write("x,x,x [2],,Column_4\n1,2,3,4,5\n"))
        self.assertTrue(ds.frame.columns.is_unique)
        self.assertEqual(ds.frame.iloc[0].tolist(), [1, 2, 3, 4, 5])
        self.assertGreaterEqual(len(ds.notices), 2)

    def test_missing_infinite_mixed_and_precision(self):
        ds = load_dataset(self.write("x,y,z\n1,inf,1.2345678901234567\n,2,3e-120\n3,text,4\n"))
        self.assertEqual(ds.missing_count, 1)
        self.assertEqual(ds.columns[1].kind, "text")
        self.assertEqual(ds.frame.z.iloc[0], float("1.2345678901234567"))
        ds = load_dataset(self.write("x\ninf\n-inf\n1\n"))
        self.assertEqual(ds.infinite_count, 2)

    def test_cancel_missing_file_and_iso_dates(self):
        event = threading.Event()
        event.set()
        with self.assertRaises(CancelledError):
            load_dataset(self.write("x\n1\n"), cancel=event)
        with self.assertRaises(DataError):
            load_dataset(Path(self.temp.name) / "missing.csv")
        ds = load_dataset(
            self.write("date,x\n2026-01-01,1\n"), ImportOptions(date_columns=("date",))
        )
        self.assertEqual(ds.columns[0].kind, "datetime")

    def test_nullable_large_integer_import_preserves_exact_csv_and_dat(self):
        cases = (
            (
                "csv",
                "id,y\n9007199254740992,1\n9007199254740993,2\n,3\n",
            ),
            (
                "dat",
                '# id y\n9007199254740992 1\n9007199254740993 2\n"" 3\n',
            ),
        )
        for suffix, content in cases:
            with self.subTest(suffix=suffix):
                ds = load_dataset(self.write(content, f"ids.{suffix}"))
                self.assertEqual(str(ds.frame["id"].dtype), "Int64")
                self.assertEqual(ds.frame["id"].iloc[0], 2**53)
                self.assertEqual(ds.frame["id"].iloc[1], 2**53 + 1)
                self.assertTrue(pd.isna(ds.frame["id"].iloc[2]))
                self.assertEqual(ds.columns[0].kind, "numeric")
                self.assertEqual(ds.columns[0].missing, 1)
                self.assertEqual(
                    build_filter_mask(
                        ds.frame,
                        (FilterRule("id", upper=2**53),),
                    ).tolist(),
                    [True, False, False],
                )

    def test_nullable_integer_limits_and_null_markers(self):
        cases = (
            (
                "signed.csv",
                f"id,y\n{-2**63},1\n{-2**63 + 1},2\n,3\n",
                "Int64",
                [-2**63, -2**63 + 1],
                FilterRule("id", lower=-2**63 + 1),
                [False, True, False],
            ),
            (
                "signed_max.csv",
                f"id,y\n{2**63 - 2},1\n{2**63 - 1},2\n,3\n",
                "Int64",
                [2**63 - 2, 2**63 - 1],
                FilterRule("id", lower=2**63 - 1),
                [False, True, False],
            ),
            (
                "unsigned.csv",
                f"id,y\n{2**63},1\n{2**64 - 1},2\n,3\n",
                "UInt64",
                [2**63, 2**64 - 1],
                FilterRule("id", upper=2**63),
                [True, False, False],
            ),
            (
                "small.csv",
                "id,y\n1,1\nNA,2\n2,3\n",
                "Int64",
                [1, 2],
                FilterRule("id", upper=1),
                [True, False, False],
            ),
        )
        for name, content, dtype, values, rule, expected in cases:
            with self.subTest(name=name):
                ds = load_dataset(self.write(content, name))
                self.assertEqual(str(ds.frame["id"].dtype), dtype)
                present = [int(value) for value in ds.frame["id"].dropna().tolist()]
                self.assertEqual(present, values)
                self.assertEqual(ds.frame["id"].isna().sum(), 1)
                self.assertEqual(build_filter_mask(ds.frame, (rule,)).tolist(), expected)

    def test_non_integer_columns_keep_existing_inference(self):
        path = self.write(
            "float,scientific,flag,mixed,date,all_missing\n"
            "1.0,1e3,True,1,2026-01-01,\n"
            "2.5,2e3,False,text,2026-01-02,\n"
            ",,,,,\n"
        )
        ds = load_dataset(path, ImportOptions(date_columns=("date",)))
        self.assertEqual(str(ds.frame["float"].dtype), "float64")
        self.assertEqual(str(ds.frame["scientific"].dtype), "float64")
        self.assertEqual(str(ds.frame["flag"].dtype), "object")
        self.assertEqual(str(ds.frame["mixed"].dtype), "object")
        self.assertEqual(str(ds.frame["all_missing"].dtype), "float64")
        self.assertEqual(ds.columns[4].kind, "datetime")
        self.assertEqual(ds.frame["float"].dropna().tolist(), [1.0, 2.5])
        self.assertEqual(ds.frame["scientific"].dropna().tolist(), [1000.0, 2000.0])
        self.assertEqual(ds.frame["mixed"].dropna().tolist(), ["1", "text"])

    def test_unrepresentable_nullable_integer_columns_are_rejected(self):
        cases = (
            (
                "above_uint64.csv",
                f"id,y\n{2**64},1\n{2**64 + 1},2\n,3\n",
            ),
            (
                "mixed_signed_range.csv",
                f"id,y\n-1,1\n{2**63},2\n,3\n",
            ),
        )
        for name, content in cases:
            with self.subTest(name=name):
                with self.assertRaisesRegex(
                    DataError,
                    "cannot be represented exactly|64-bit integer",
                ):
                    load_dataset(self.write(content, name))

    def test_state_atomic_replacement_and_stale_results(self):
        state = AppState()
        a = load_dataset(self.write("x,y\n1,2\n3,4\n"))
        b = load_dataset(self.write("a,b\n5,6\n", "b.csv"))
        notices = []
        state.subscribe(lambda reason: notices.append((reason, state.dataset.path.name)))
        ticket = state.begin_load()
        self.assertTrue(state.commit_dataset(ticket, a))
        rev = state.revision
        rules = (FilterRule("x", 2, None),)
        state.commit_filters(rev, rules, np.array([False, True]))
        self.assertEqual(state.selected_count, 1)
        self.assertFalse(state.mask.flags.writeable)
        stale = state.begin_load()
        current = state.begin_load()
        self.assertFalse(state.commit_dataset(stale, b))
        self.assertIs(state.dataset, a)
        state.cancel_load()
        self.assertFalse(state.commit_dataset(current, b))
        self.assertTrue(state.commit_dataset(state.begin_load(), b))
        self.assertEqual(state.filters, ())
        self.assertIsNone(state.mask)
        self.assertFalse(state.commit_filters(rev, rules, np.array([True])))
        self.assertEqual(notices[-1], ("dataset", "b.csv"))


if __name__ == "__main__":
    unittest.main()
